#!/usr/bin/env python3

import importlib.util
import unittest
from pathlib import Path


MODULE_PATH = Path(__file__).with_name("verify_baseline.py")
SPEC = importlib.util.spec_from_file_location("verify_baseline", MODULE_PATH)
assert SPEC is not None and SPEC.loader is not None
verify_baseline = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(verify_baseline)


class NormalizeGeneratedHeaderTests(unittest.TestCase):
    def test_normalizes_only_generated_header(self) -> None:
        source = b"; generated by OrcaSlicer on 2026-11-03\nG28\n"
        expected = b"; generated by <normalized>\nG28\n"
        self.assertEqual(verify_baseline.normalize_generated_header(source), expected)

    def test_preserves_crlf(self) -> None:
        source = b"; generated by OrcaSlicer\r\nG28\r\n"
        expected = b"; generated by <normalized>\r\nG28\r\n"
        self.assertEqual(verify_baseline.normalize_generated_header(source), expected)

    def test_rejects_missing_header(self) -> None:
        with self.assertRaises(verify_baseline.VerificationError):
            verify_baseline.normalize_generated_header(b"G28\n")

    def test_rejects_multiple_headers(self) -> None:
        with self.assertRaises(verify_baseline.VerificationError):
            verify_baseline.normalize_generated_header(
                b"; generated by first\n; generated by second\n"
            )


if __name__ == "__main__":
    unittest.main()
